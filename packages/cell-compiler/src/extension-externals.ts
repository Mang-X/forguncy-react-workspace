/**
 * The compilation projection of #12's `extension` external mapping.
 *
 * Decision source: GitHub Issue #12 — "Spec: `extension` dependencies as external
 * modules + `frontendLibraries` metadata"
 * (https://github.com/Mang-X/forguncy-react-workspace/issues/12), which is itself
 * downstream of:
 * - #4 "application ownership boundaries and dependency strategy semantics"
 *   — https://github.com/Mang-X/forguncy-react-workspace/issues/4
 * - #5 "establish the ReactCellType target/runtime contract on Forguncy 12.0.100"
 *   — https://github.com/Mang-X/forguncy-react-workspace/issues/5
 * - #6 "generated ReactCellType artifact and compiler boundary"
 *   — https://github.com/Mang-X/forguncy-react-workspace/issues/6
 *
 * `core` owns *which* import a verified extension stands in for, what keeps that
 * mapping independent of library load order, and the diagnostic vocabulary. This
 * module owns what the compilation path does with that: the module handed to the
 * bundler in place of the dependency, and the externals plan a resolver hook is
 * wired from.
 *
 * Three things here are deliberate, and each is the answer to one of #12's
 * acceptance criteria:
 *
 * 1. **The interposition is keyed on the specifier and is a pure function of the
 *    mapping.** No function here takes authored source as an argument, so nothing
 *    can rewrite one (#12: "Compiler external mapping can preserve normal source
 *    imports") and there is no place for a package-specific AST rule to live.
 *    {@link planExtensionExternals} derives its set by walking the mapping table,
 *    so a new row is the whole of the change.
 * 2. **The generated module exports the page object itself, resolved while its own body
 *    runs, and reads no other extension's global.** Those two together make "no
 *    dependency on extension load order is introduced" a property of the emitted code
 *    rather than an argument about how a page happened to load things — see `core`'s
 *    `EXTENSION_LOAD_ORDER_RULES`, which this module implements, and
 *    `EXTENSION_EXTERNAL_INTEROP_BEHAVIOUR`, which is what rules out the two shapes a
 *    first design reaches for (a lazily-resolving proxy, and a narrowed view).
 * 3. **The library reference is derived, not assumed.** The plan reports the
 *    `frontendLibraries` metadata #6 canonicalizes from the same decisions, and
 *    reports an import the mapping intercepts but nothing declares, because that is
 *    the state in which the artifact reads a global no cell asked the page to load.
 *
 * Scope note: this module generates the interposed modules and plans the externals,
 * and audits a decision list against the mapping table. It does not drive a bundler,
 * assemble an artifact, or emit a diagnostic into #6's artifact report — wiring the
 * externals into the compile boundary is the compiler MVP's job (#7), exactly as
 * #9's bridge was left to it, and asserting an externals diagnostic through
 * `CellArtifactDiagnostic` would put two vocabularies in one report before anyone has
 * decided how they compose. It also does not package an extension; that is
 * `MangMax/forguncy-frontend-library`'s.
 */

