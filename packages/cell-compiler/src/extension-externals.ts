/**
 * The first line of every module this file generates.
 *
 * The same reasoning #6 gives for the artifact banner: a file a machine composed has
 * to be recognizable as one, or a reviewer reading a bundle cannot tell generated
 * interposition from a dependency that happens to look like it.
 */
export const EXTENSION_EXTERNAL_GENERATED_BANNER =
  "/* generated by @forguncy-react-workspace/cell-compiler from the extension externals contract (#12) — do not edit */";

// ---------------------------------------------------------------------------
// The generated runtime error
// ---------------------------------------------------------------------------

/**
 * The one condition a generated module can report at runtime.
 *
 * One, not a table: every other code in `core`'s vocabulary is a build-time or
 * sync-time finding, and a generated module that could throw one of those would be
 * reporting a table problem from inside the page.
 */
const EXTENSION_RUNTIME_ERROR_CODE = "extension-global-missing" as const;

/**
 * The structured-error factory, generated from `core`'s rule table.
 *
 * Structured the way an Agent needs it — a stable `code`, the specifier that needed
 * the global, the library the reference names and the global itself — because a
 * message string is not branchable. The wording comes from the rule table rather
 * than from a sentence written here, so a runtime failure and the sync-time finding
 * that should have prevented it cannot drift.
 */
function renderExtensionErrorFactory(): string {
  const rule = extensionExternalDiagnosticRule(EXTENSION_RUNTIME_ERROR_CODE);
  // The rule's wording is embedded as a JSON string literal rather than pasted into
  // a hand-written literal: a remediation that later gains a quote or a newline
  // would otherwise turn the generated module into a syntax error, which is the one
  // failure mode a machine-composed file must not have.
  const ruleText = JSON.stringify(`${rule.states} ${rule.remediation}`);
  return [
    `function __fgcExtensionError(specifier, libraryId, globalName) {`,
    `  var error = new Error(`,
    `    "[extension-externals] ${EXTENSION_RUNTIME_ERROR_CODE}: " + specifier +`,
    `    " is provided by the frontend library \\"" + libraryId + "\\", which publishes the page global \\"" + globalName +`,
    `    "\\", and that global is not present. " + ${ruleText}`,
    `  );`,
    `  error.name = "ExtensionExternalError";`,
    `  error.code = ${JSON.stringify(EXTENSION_RUNTIME_ERROR_CODE)};`,
    `  error.specifier = specifier;`,
    `  error.libraryId = libraryId;`,
    `  error.globalName = globalName;`,
    `  error.fixOwner = ${JSON.stringify(rule.fixOwner)};`,
    `  return error;`,
    `}`,
  ].join("\n");
}

// ---------------------------------------------------------------------------
// The interposed module
// ---------------------------------------------------------------------------

/**
 * The module the bundler loads in place of an `extension`-decided dependency.
 *
 * Three lines of substance — resolve the global, refuse without it, export it — and
 * every one of them is forced by something measured rather than chosen:
 *
 * - **The page object itself, not a wrapper and not a copy.** It is the only shape that
 *   preserves member identity across cells (`TanStackQuery.QueryClient` is one class on
 *   the page, and a wrapper would hand out a different object however faithfully it
 *   forwarded), and it is the only shape that survives a consumer's namespace import.
 *   See the next bullet for why that second point is a hard constraint and not a
 *   preference.
 * - **Resolved while this module's body runs, and failing loudly without the global.**
 *   The first version of this module was the opposite — a lazily-resolving `Proxy` that
 *   answered member access and never threw at evaluation — and it was wrong for a reason
 *   no test of the module in isolation could show. For `import * as ns from "<cjs module>"`
 *   the bundler emits `__toESM`, which enumerates `module.exports` through
 *   `Object.getOwnPropertyNames` **once**, at namespace-creation time, and builds a
 *   namespace from what it finds. A proxy whose `ownKeys` answers "nothing yet" therefore
 *   produces a namespace that can never contain the extension's members, and the authored
 *   `import { useQuery }` silently reads `undefined` for the rest of the page's life.
 *   `__esModule` does not help: in the bundler's runtime it only decides whether a
 *   `default` entry is added. Exporting the real object makes the enumeration find the
 *   real names, and a missing global becomes a named error at one moment instead of an
 *   `undefined` at every use. `core`'s `EXTENSION_EXTERNAL_INTEROP_BEHAVIOUR` holds the
 *   mechanism and the regression that pins it.
 * - **No member inventory.** #9's `verified-member-view` exists where runtime evidence
 *   produced an inventory of the host object's members; nothing comparable exists for an
 *   extension, whose surface is the vendor module's. Exporting the whole object is the
 *   honest form of "we verified the extension, not its member list".
 *
 * `moduleId` is the id the source actually imported, not the mapping's primary
 * package: a row can cover more than one package (`@tanstack/query-core` rides on the
 * `@tanstack/react-query` row), and a failure has to name the import the author
 * wrote.
 */
export function renderExtensionExternalModule(mapping: ExtensionExternalMapping, moduleId: string): string {
  if (!extensionModuleIds(mapping).includes(moduleId)) {
    throw new ExtensionExternalContractError(
      `Extension mapping "${mapping.packageName}" does not intercept "${moduleId}", so there is no module to render for it.`,
    );
  }

  const specifier = JSON.stringify(moduleId);
  const libraryId = JSON.stringify(mapping.libraryId);
  const globalName = JSON.stringify(mapping.globalName);

  return `${[
    EXTENSION_EXTERNAL_GENERATED_BANNER,
    `// ${specifier} is provided by the Forguncy frontend library ${libraryId}, which publishes`,
    `// the page global ${globalName}. The npm implementation is not in this artifact: the`,
    `// authored import is answered by the page object below, exported as it is.`,
    `//`,
    `// The global is resolved at ${EXTENSION_GLOBAL_READ_TIMING}. Reading it later would not make`,
    `// this module safer, only quieter: a consumer that imports a namespace enumerates this`,
    `// module once, when the namespace is created, so a member name that is not an own`,
    `// property at that moment never appears in the namespace at all — the authored import`,
    `// would read \`undefined\` rather than fail. #5 records that a cell's own declared`,
    `// libraries resolve before that cell's entry runs, so the global is there; if it is not,`,
    `// this module says so by name instead of leaving every use to fail on its own.`,
    `//`,
    `// No other library's global is read anywhere below, which is why this artifact cannot`,
    `// depend on one extension being loaded before another.`,
    renderExtensionErrorFactory(),
    `var __fgcExtensionValue = globalThis[${globalName}];`,
    `if (__fgcExtensionValue === undefined) {`,
    `  throw __fgcExtensionError(${specifier}, ${libraryId}, ${globalName});`,
    `}`,
    `module.exports = __fgcExtensionValue;`,
  ].join("\n")}\n`;
}

