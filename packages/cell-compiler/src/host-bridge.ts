/**
 * The generated JSX runtime adapter.
 *
 * The two-parameter/two-case rule below is the one
 * `MangMax/forguncy-react-library` verified and its regression test exists to keep:
 * `jsx(type, props, key)` and `createElement(type, config, children)` disagree
 * about the third parameter, so the key is never forwarded as the third argument
 * and no third argument is passed when there is no key. `core`'s
 * `JSX_RUNTIME_ADAPTER_RULES` is the contract this code implements; the comments
 * here are the *why* for a reader who has the generated file and not the Spec.
 *
 * Two additions to the verified form, both from #9 rather than from taste:
 *
 * - the host lookup is **lazy**, so evaluating the module while `globalThis.React`
 *   is absent does not throw (`evaluation-must-not-throw`) while a call that
 *   actually needs React fails with the bridge's structured error;
 * - `Fragment` is exposed through a **getter**, because it is a *guarded* member —
 *   #5 never read `React.Fragment` off the host object, so the bridge checks it on
 *   access instead of binding a possibly-undefined snapshot at module load.
 *
 * `jsxs` and `jsxDEV` share the implementation. The dev-only arguments are accepted
 * and ignored: they carry debugging metadata, and reproducing it would mean
 * reimplementing a React-internal surface.
 *
 * `moduleId` is the id the source actually imported. Both runtime ids share this
 * adapter, so it is what makes a failure from a dev build name
 * `react/jsx-dev-runtime` rather than the row's first id.
 */
export function renderHostBridgeAdapterModule(mapping: HostBridgeAdapterMapping, moduleId: string): string {
  // The adapter id decides which host member is the delegate. `jsx-runtime` means the
  // host React object's `createElement` — a second adapter id would need its own
  // delegate here, which is why the delegate is not a mapping field: a mapping says
  // which members are *required*, and the adapter knows what to do with them.
  const globalName = "React";
  const createElement = mapping.requiredHostMembers.includes("createElement") ? "createElement" : undefined;

  if (!hostBridgeModuleIds(mapping).includes(moduleId)) {
    throw new HostBridgeContractError(
      `Host bridge adapter "${mapping.specifier}" does not intercept "${moduleId}", so there is no module to render for it.`,
    );
  }

  if (createElement === undefined) {
    throw new HostBridgeContractError(
      `Host bridge adapter "${mapping.specifier}" declares no "createElement" among its required host members, so the generated adapter would have nothing to delegate to.`,
    );
  }

  const fragmentGuarded = (mapping.guardedMembers ?? []).includes("Fragment");

  const lines = [
    HOST_BRIDGE_GENERATED_BANNER,
    renderErrorFactories(["host-global-missing", "host-global-incompatible"]),
    ``,
    `function __fgcHostBridgeReact() {`,
    `  var value = globalThis[${JSON.stringify(globalName)}];`,
    `  if (value === undefined) {`,
    `    throw __fgcHostBridgeErrorMissing(${JSON.stringify(moduleId)}, ${JSON.stringify(globalName)}, undefined);`,
    `  }`,
    `  return value;`,
    `}`,
    ``,
    `// jsx(type, props, key) — the third parameter is the key, NOT children, and`,
    `// createElement's third parameter IS children. Passing the key through as the`,
    `// third argument sets children to the key and drops the key.`,
    `function __fgcHostBridgeJsx(type, props, key) {`,
    `  var React = __fgcHostBridgeReact();`,
    `  if (key === undefined) {`,
    `    // Exactly two arguments: an explicit undefined third one would take`,
    `    // createElement's children branch and overwrite props.children.`,
    `    return React.${createElement}(type, props);`,
    `  }`,
    `  return React.${createElement}(type, Object.assign({}, props, { key: key }));`,
    `}`,
    ``,
    `module.exports = {`,
    `  jsx: __fgcHostBridgeJsx,`,
    `  jsxs: __fgcHostBridgeJsx,`,
    `  jsxDEV: __fgcHostBridgeJsx,`,
    `};`,
  ];

  if (fragmentGuarded) {
    lines.push(
      ``,
      `// Fragment is a guarded member: #5 did not observe it on the host object, so it`,
      `// is checked on access rather than bound as a snapshot at module load.`,
      `Object.defineProperty(module.exports, "Fragment", {`,
      `  enumerable: true,`,
      `  get: function () {`,
      `    var React = __fgcHostBridgeReact();`,
      `    if (React.Fragment === undefined) {`,
      `      throw __fgcHostBridgeErrorIncompatible(${JSON.stringify(moduleId)}, ${JSON.stringify(globalName)}, "Fragment");`,
      `    }`,
      `    return React.Fragment;`,
      `  },`,
      `});`,
    );
  }

  return `${lines.join("\n")}\n`;
}

/**
 * The interposed module for a mapping, whichever kind it is.
 *
 * Dispatch is on `kind`, which is the mapping's declaration of whether a page
 * object has the module's shape. Nothing inspects the specifier to decide.
 */
/**
 * The interposed module for one intercepted module id.
 *
 * Dispatch is on the module id's declared shape, which is the mapping's own
 * statement of whether the import is the host object, a view over it, or generated
 * code. Nothing inspects the specifier to decide, and a module id the table does not
 * intercept is refused rather than rendered.
 */
export function renderHostBridgeModule(mapping: HostBridgeMapping, moduleId: string): string {
  if (mapping.kind === "jsx-runtime-adapter") {
    return renderHostBridgeAdapterModule(mapping, moduleId);
  }
  return renderHostBridgeGlobalModule(mapping, moduleId);
}

